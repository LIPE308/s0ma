-- PostgreSQL / Supabase. Apply to a NEW, empty SOMA project. No demo data.
BEGIN;
-- MySQL 8.4. Valores monetários são centavos (inteiros), nunca FLOAT.
CREATE TABLE IF NOT EXISTS usuarios (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(150) NOT NULL,
  email VARCHAR(150) NOT NULL UNIQUE,
  senha_resumo VARCHAR(128) NOT NULL,
  senha_sal VARCHAR(32) NOT NULL,
  telefone VARCHAR(30) NOT NULL DEFAULT '',
  regiao VARCHAR(150) NOT NULL DEFAULT '',
  novidades SMALLINT CHECK (novidades IN (0,1)) NOT NULL DEFAULT 0,
  administrador SMALLINT CHECK (administrador IN (0,1)) NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS sessoes (
  resumo_token VARCHAR(64) PRIMARY KEY,
  usuario_id INT NOT NULL,
  expira_em BIGINT NOT NULL,
  FOREIGN KEY (usuario_id) REFERENCES usuarios(id)
);
CREATE TABLE IF NOT EXISTS campanhas (
  id VARCHAR(36) PRIMARY KEY,
  usuario_id INT NOT NULL,
  titulo VARCHAR(150) NOT NULL,
  descricao TEXT NOT NULL,
  categoria VARCHAR(50) NOT NULL,
  regiao VARCHAR(150) NOT NULL,
  prazo VARCHAR(30) NOT NULL,
  instrucoes VARCHAR(2000) NOT NULL DEFAULT '',
  evento VARCHAR(1000) NOT NULL DEFAULT '',
  estado VARCHAR(40) CHECK (estado IN ('rascunho','ativa','encerrada','suspensa','ajustes')) NOT NULL DEFAULT 'ativa',
  motivo VARCHAR(1000) NOT NULL DEFAULT '',
  estado_antes_moderacao VARCHAR(40) CHECK (estado_antes_moderacao IN ('ativa','encerrada')) DEFAULT NULL,
  criada_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (usuario_id) REFERENCES usuarios(id)
);
CREATE TABLE IF NOT EXISTS necessidades (
  id VARCHAR(36) PRIMARY KEY,
  campanha_id VARCHAR(36) NOT NULL,
  nome VARCHAR(150) NOT NULL,
  tipo VARCHAR(40) CHECK (tipo IN ('objeto','tarefa','dinheiro')) NOT NULL,
  meta INT NOT NULL CHECK (meta > 0),
  recebido INT NOT NULL DEFAULT 0 CHECK (recebido >= 0),
  tipo_meta VARCHAR(40) CHECK (tipo_meta IN ('fechada','aberta')) NOT NULL DEFAULT 'fechada',
  prioridade VARCHAR(20) NOT NULL DEFAULT 'Normal',
  prazo VARCHAR(30) NOT NULL DEFAULT '',
  descricao VARCHAR(2000) NOT NULL DEFAULT '',
  FOREIGN KEY (campanha_id) REFERENCES campanhas(id)
);
CREATE TABLE IF NOT EXISTS ajudas (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id INT NOT NULL,
  campanha_id VARCHAR(36) NOT NULL,
  necessidade_id VARCHAR(36),
  tipo VARCHAR(40) CHECK (tipo IN ('objeto','tarefa','acao')) NOT NULL,
  quantidade INT NOT NULL CHECK (quantidade > 0),
  recebido INT NOT NULL DEFAULT 0 CHECK (recebido >= 0),
  entrega VARCHAR(300) NOT NULL DEFAULT '',
  horario VARCHAR(100) NOT NULL DEFAULT '',
  observacao VARCHAR(2000) NOT NULL DEFAULT '',
  estado VARCHAR(40) CHECK (estado IN ('reservado','em_andamento','realizado','cancelado')) NOT NULL DEFAULT 'reservado',
  criada_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (usuario_id) REFERENCES usuarios(id),
  FOREIGN KEY (campanha_id) REFERENCES campanhas(id),
  FOREIGN KEY (necessidade_id) REFERENCES necessidades(id),
  CHECK (recebido <= quantidade)
);
CREATE TABLE IF NOT EXISTS atualizacoes (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campanha_id VARCHAR(36) NOT NULL,
  usuario_id INT NOT NULL,
  titulo VARCHAR(150) NOT NULL,
  relato TEXT NOT NULL,
  criada_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (campanha_id) REFERENCES campanhas(id),
  FOREIGN KEY (usuario_id) REFERENCES usuarios(id)
);
CREATE TABLE IF NOT EXISTS pagamentos (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id INT NOT NULL,
  necessidade_id VARCHAR(36) NOT NULL,
  valor INT NOT NULL CHECK (valor >= 1000),
  taxa_soma INT NOT NULL,
  taxa_provedor INT NOT NULL,
  valor_liquido INT NOT NULL CHECK (valor_liquido > 0),
  meio VARCHAR(40) CHECK (meio IN ('Pix','Crédito','Débito','Simulação')) NOT NULL,
  estado VARCHAR(40) CHECK (estado IN ('pendente','confirmado','cancelado','reembolsado')) NOT NULL DEFAULT 'pendente',
  criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (usuario_id) REFERENCES usuarios(id),
  FOREIGN KEY (necessidade_id) REFERENCES necessidades(id)
);
CREATE TABLE IF NOT EXISTS repasses (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campanha_id VARCHAR(36) NOT NULL,
  usuario_id INT NOT NULL,
  valor INT NOT NULL CHECK (valor > 0),
  finalidade VARCHAR(1000) NOT NULL,
  estado VARCHAR(40) CHECK (estado IN ('solicitado','concluido','recusado','cancelado')) NOT NULL DEFAULT 'solicitado',
  motivo VARCHAR(1000) NOT NULL DEFAULT '',
  criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (campanha_id) REFERENCES campanhas(id),
  FOREIGN KEY (usuario_id) REFERENCES usuarios(id)
);
CREATE TABLE IF NOT EXISTS denuncias (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campanha_id VARCHAR(36) NOT NULL,
  usuario_id INT NOT NULL,
  motivo VARCHAR(150) NOT NULL,
  relato TEXT NOT NULL,
  estado VARCHAR(40) CHECK (estado IN ('pendente','analisada')) NOT NULL DEFAULT 'pendente',
  criada_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (campanha_id) REFERENCES campanhas(id),
  FOREIGN KEY (usuario_id) REFERENCES usuarios(id)
);
CREATE TABLE IF NOT EXISTS avisos (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id INT NOT NULL,
  mensagem VARCHAR(1000) NOT NULL,
  lido SMALLINT CHECK (lido IN (0,1)) NOT NULL DEFAULT 0,
  criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (usuario_id) REFERENCES usuarios(id)
);
CREATE TABLE IF NOT EXISTS operacoes (
  usuario_id INT NOT NULL,
  chave VARCHAR(100) NOT NULL,
  resumo CHAR(64) NOT NULL,
  resposta TEXT,
  criada_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (usuario_id, chave),
  FOREIGN KEY (usuario_id) REFERENCES usuarios(id)
);


CREATE TABLE IF NOT EXISTS revisoes_urgencia (
 id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, campanha_id VARCHAR(36) NOT NULL, autor_id INT NOT NULL,
 relato VARCHAR(4000) NOT NULL, estado VARCHAR(40) CHECK (estado IN ('pendente','revisada')) NOT NULL DEFAULT 'pendente',
 criterios TEXT, categoria VARCHAR(20) NOT NULL DEFAULT 'Regular', pontos INT NOT NULL DEFAULT 0,
 justificativa VARCHAR(2000) NOT NULL DEFAULT '', revisor_id INT, criada_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 revisada_em TIMESTAMP NULL, valida_ate TIMESTAMP NULL,
 FOREIGN KEY (campanha_id) REFERENCES campanhas(id), FOREIGN KEY (autor_id) REFERENCES usuarios(id), FOREIGN KEY (revisor_id) REFERENCES usuarios(id)
);
CREATE TABLE IF NOT EXISTS receitas_solidarias (
 id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, referencia VARCHAR(100) NOT NULL UNIQUE, valor INT NOT NULL,
 autor_id INT NOT NULL, resultado TEXT NOT NULL, criada_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (autor_id) REFERENCES usuarios(id)
);
CREATE TABLE IF NOT EXISTS distribuicoes_solidarias (
 receita_id INT NOT NULL, campanha_id VARCHAR(36) NOT NULL, valor INT NOT NULL,
 PRIMARY KEY (receita_id,campanha_id), FOREIGN KEY (receita_id) REFERENCES receitas_solidarias(id), FOREIGN KEY (campanha_id) REFERENCES campanhas(id)
);
CREATE TABLE IF NOT EXISTS localizacoes_publicas (
 campanha_id VARCHAR(36) PRIMARY KEY, uf CHAR(2) NOT NULL,
 FOREIGN KEY (campanha_id) REFERENCES campanhas(id)
);
CREATE TABLE IF NOT EXISTS imagens_campanha (
 campanha_id VARCHAR(36) PRIMARY KEY, imagem TEXT NOT NULL,
 FOREIGN KEY (campanha_id) REFERENCES campanhas(id)
);
CREATE TABLE IF NOT EXISTS identidades_google (
 sub VARCHAR(255) PRIMARY KEY, usuario_id INT NOT NULL UNIQUE,
 FOREIGN KEY (usuario_id) REFERENCES usuarios(id)
);
CREATE TABLE IF NOT EXISTS marcos_financeiros (
 campanha_id VARCHAR(36) NOT NULL, chave VARCHAR(80) NOT NULL,
 alcancado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY (campanha_id,chave), FOREIGN KEY (campanha_id) REFERENCES campanhas(id)
);

-- Extensão aditiva SOMA 2.0: valores em centavos, nenhum dinheiro real.
CREATE TABLE IF NOT EXISTS soma_migracoes (
  chave VARCHAR(60) PRIMARY KEY,
  aplicada_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS perfis (
  usuario_id INT PRIMARY KEY,
  tipo VARCHAR(40) CHECK (tipo IN ('pessoa','instituicao')) NOT NULL DEFAULT 'pessoa',
  biografia VARCHAR(1200) NOT NULL DEFAULT '',
  nome_instituicao VARCHAR(150) NOT NULL DEFAULT '',
  adulto SMALLINT CHECK (adulto IN (0,1)) DEFAULT NULL,
  publico SMALLINT CHECK (publico IN (0,1)) NOT NULL DEFAULT 0,
  local_publico SMALLINT CHECK (local_publico IN (0,1)) NOT NULL DEFAULT 0,
  apoios_publicos SMALLINT CHECK (apoios_publicos IN (0,1)) NOT NULL DEFAULT 0,
  cor VARCHAR(40) CHECK (cor IN ('royal','verde','terracota')) NOT NULL DEFAULT 'royal',
  avatar_id VARCHAR(36),
  capa_id VARCHAR(36),
  onboarding_concluido SMALLINT NOT NULL DEFAULT 0 CHECK (onboarding_concluido IN (0,1)),
  foto_google VARCHAR(600),
  usar_foto_google SMALLINT NOT NULL DEFAULT 0 CHECK (usar_foto_google IN (0,1)),
  FOREIGN KEY (usuario_id) REFERENCES usuarios(id)
);
CREATE TABLE IF NOT EXISTS campanhas_detalhes (
  campanha_id VARCHAR(36) PRIMARY KEY,
  uf CHAR(2) NOT NULL DEFAULT '',
  municipio VARCHAR(100) NOT NULL DEFAULT '',
  mapa_autorizado SMALLINT CHECK (mapa_autorizado IN (0,1)) NOT NULL DEFAULT 0,
  imagem_id VARCHAR(36),
  visualizacoes INT NOT NULL DEFAULT 0,
  submetida SMALLINT CHECK (submetida IN (0,1)) NOT NULL DEFAULT 0,
  FOREIGN KEY (campanha_id) REFERENCES campanhas(id)
);
CREATE TABLE IF NOT EXISTS arquivos (
  id VARCHAR(36) PRIMARY KEY,
  usuario_id INT NOT NULL,
  campanha_id VARCHAR(36),
  nome VARCHAR(150) NOT NULL,
  mime VARCHAR(40) NOT NULL,
  finalidade VARCHAR(40) CHECK (finalidade IN ('documento','campanha','avatar','capa')) NOT NULL,
  publico SMALLINT CHECK (publico IN (0,1)) NOT NULL DEFAULT 0,
  tamanho INT NOT NULL,
  conteudo BYTEA NOT NULL,
  criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (usuario_id) REFERENCES usuarios(id),
  FOREIGN KEY (campanha_id) REFERENCES campanhas(id)
);
CREATE TABLE IF NOT EXISTS urgencias (
  campanha_id VARCHAR(36) PRIMARY KEY,
  natureza VARCHAR(40) CHECK (natureza IN ('vida','moradia','alimentacao','educacao','outros')) NOT NULL,
  consequencias VARCHAR(3000) NOT NULL,
  prazo_limite DATE NOT NULL,
  recursos_disponiveis INT NOT NULL DEFAULT 0,
  estado VARCHAR(40) CHECK (estado IN ('pendente','revisada','recurso')) NOT NULL DEFAULT 'pendente',
  classe VARCHAR(40) CHECK (classe IN ('regular','moderada','critica')) NOT NULL DEFAULT 'regular',
  recomendacao VARCHAR(40) CHECK (recomendacao IN ('regular','moderada','critica')) NOT NULL DEFAULT 'regular',
  pontos INT NOT NULL DEFAULT 0,
  evidencia_verificada SMALLINT CHECK (evidencia_verificada IN (0,1)) NOT NULL DEFAULT 0,
  evidencia_valida_ate DATE,
  revisado_por INT,
  justificativa VARCHAR(3000) NOT NULL DEFAULT '',
  revisada_em TIMESTAMP NULL,
  FOREIGN KEY (campanha_id) REFERENCES campanhas(id),
  FOREIGN KEY (revisado_por) REFERENCES usuarios(id)
);
CREATE TABLE IF NOT EXISTS urgencia_historico (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campanha_id VARCHAR(36) NOT NULL,
  usuario_id INT NOT NULL,
  acao VARCHAR(40) NOT NULL,
  dados JSON NOT NULL,
  criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (campanha_id) REFERENCES campanhas(id),
  FOREIGN KEY (usuario_id) REFERENCES usuarios(id)
);
CREATE TABLE IF NOT EXISTS auditoria (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id INT,
  campanha_id VARCHAR(36),
  acao VARCHAR(60) NOT NULL,
  dados JSON NOT NULL,
  criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (usuario_id) REFERENCES usuarios(id),
  FOREIGN KEY (campanha_id) REFERENCES campanhas(id)
);
CREATE TABLE IF NOT EXISTS receitas_publicitarias (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  referencia VARCHAR(120) NOT NULL UNIQUE,
  bruto INT NOT NULL CHECK (bruto > 0),
  tributos INT NOT NULL DEFAULT 0 CHECK (tributos >= 0),
  custos INT NOT NULL DEFAULT 0 CHECK (custos >= 0),
  justificativa VARCHAR(1000) NOT NULL,
  estado VARCHAR(40) CHECK (estado IN ('pendente','confirmada','distribuida')) NOT NULL DEFAULT 'pendente',
  modo VARCHAR(40) CHECK (modo IN ('simulado')) NOT NULL DEFAULT 'simulado',
  usuario_id INT NOT NULL,
  criada_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  confirmada_em TIMESTAMP NULL,
  FOREIGN KEY (usuario_id) REFERENCES usuarios(id),
  CHECK (bruto >= tributos + custos)
);
CREATE TABLE IF NOT EXISTS distribuicoes (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  receita_id INT NOT NULL,
  campanha_id VARCHAR(36) NOT NULL,
  necessidade_id VARCHAR(36) NOT NULL,
  valor INT NOT NULL CHECK (valor > 0),
  peso DECIMAL(14,6) NOT NULL,
  criterios JSON NOT NULL,
  criada_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (receita_id, necessidade_id),
  FOREIGN KEY (receita_id) REFERENCES receitas_publicitarias(id),
  FOREIGN KEY (campanha_id) REFERENCES campanhas(id),
  FOREIGN KEY (necessidade_id) REFERENCES necessidades(id)
);
CREATE TABLE IF NOT EXISTS lancamentos (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campanha_id VARCHAR(36) NOT NULL,
  necessidade_id VARCHAR(36),
  origem VARCHAR(40) CHECK (origem IN ('saldo_legado','doacao','estorno','anuncio','repasse')) NOT NULL,
  referencia VARCHAR(120) NOT NULL UNIQUE,
  valor INT NOT NULL,
  modo VARCHAR(40) CHECK (modo IN ('simulado')) NOT NULL DEFAULT 'simulado',
  criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (campanha_id) REFERENCES campanhas(id),
  FOREIGN KEY (necessidade_id) REFERENCES necessidades(id)
);
CREATE TABLE IF NOT EXISTS visualizacoes (
  campanha_id VARCHAR(36) NOT NULL,
  visitante CHAR(64) NOT NULL,
  dia DATE NOT NULL,
  PRIMARY KEY (campanha_id, visitante, dia),
  FOREIGN KEY (campanha_id) REFERENCES campanhas(id)
);
CREATE TABLE IF NOT EXISTS identidades (
  usuario_id INT NOT NULL,
  provedor VARCHAR(20) NOT NULL,
  sujeito VARCHAR(255) NOT NULL,
  PRIMARY KEY (provedor, sujeito),
  UNIQUE (usuario_id, provedor),
  FOREIGN KEY (usuario_id) REFERENCES usuarios(id)
);
CREATE TABLE IF NOT EXISTS oauth_fluxos (
  resumo_estado CHAR(64) PRIMARY KEY,
  verificador VARCHAR(100) NOT NULL,
  nonce VARCHAR(100) NOT NULL,
  expira_em BIGINT NOT NULL,
  usuario_id INT,
  FOREIGN KEY (usuario_id) REFERENCES usuarios(id)
);
CREATE TABLE IF NOT EXISTS oauth_entregas (
  resumo_codigo CHAR(64) PRIMARY KEY,
  usuario_id INT NOT NULL,
  expira_em BIGINT NOT NULL,
  FOREIGN KEY (usuario_id) REFERENCES usuarios(id)
);

CREATE TABLE IF NOT EXISTS compartilhamentos (id VARCHAR(100) PRIMARY KEY,usuario_id INT NOT NULL REFERENCES usuarios(id),campanha_id VARCHAR(36) NOT NULL REFERENCES campanhas(id),canal VARCHAR(10) NOT NULL CHECK (canal IN ('link','nativo')),criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP);

