ALTER TABLE oauth_fluxos ALTER COLUMN verificador TYPE VARCHAR(128);
CREATE TABLE IF NOT EXISTS administradores_locais (
 usuario_id INT PRIMARY KEY REFERENCES usuarios(id),
 provisionado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS email_entregas (
 id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 evento VARCHAR(120) NOT NULL UNIQUE,
 usuario_id INT NOT NULL REFERENCES usuarios(id),
 campanha_id VARCHAR(36) NOT NULL REFERENCES campanhas(id),
 destinatario VARCHAR(150) NOT NULL,
 assunto VARCHAR(200) NOT NULL,
 texto TEXT NOT NULL,
 estado VARCHAR(10) NOT NULL DEFAULT 'pendente' CHECK (estado IN ('pendente','enviando','enviado','falhou')),
 tentativas INT NOT NULL DEFAULT 0,
 proxima_em BIGINT NOT NULL DEFAULT 0,
 bloqueada_em BIGINT,
 criada_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 enviada_em TIMESTAMP,
 erro_codigo VARCHAR(80) NOT NULL DEFAULT '',
 mensagem_id VARCHAR(200)
);
CREATE TABLE IF NOT EXISTS relatorios_anuncios (
 id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 provedor VARCHAR(10) NOT NULL CHECK (provedor IN ('adsense','admob')),
 conta VARCHAR(80) NOT NULL,
 inicio DATE NOT NULL,
 fim DATE NOT NULL,
 moeda CHAR(3) NOT NULL,
 estimado_centavos BIGINT NOT NULL,
 impressoes BIGINT NOT NULL DEFAULT 0,
 consultado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 usuario_id INT NOT NULL REFERENCES usuarios(id),
 UNIQUE (provedor,conta,inicio,fim,moeda)
);
CREATE INDEX IF NOT EXISTS email_fila ON email_entregas(estado,proxima_em);
CREATE INDEX IF NOT EXISTS email_entregas_usuario_idx ON email_entregas(usuario_id);
CREATE INDEX IF NOT EXISTS email_entregas_campanha_idx ON email_entregas(campanha_id);
CREATE INDEX IF NOT EXISTS relatorios_anuncios_usuario_idx ON relatorios_anuncios(usuario_id);
